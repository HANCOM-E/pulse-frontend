/**
 * 발표 자료 텍스트의 길이 한계입니다.
 *
 * ⚠️ 이 파일에 `'use client'`를 붙이지 마세요. 브라우저(`extractDeckText`)와 서버
 * (`app/api/deck-summary/route.ts`)가 **같은 값을 봐야 해서** 경계 밖에 따로 둔 파일입니다.
 *
 * 원래는 이 상수들이 `lib/deck/extractDeckText.ts` 안에 있었는데, 그 파일이 `'use client'`라
 * 서버가 import하면 Next가 값을 클라이언트 참조로 바꿔 놓습니다. 그러면 숫자가 아니게 되어
 * `text.slice(0, DECK_TEXT_MAX_LENGTH)`가 `slice(0, NaN)`이 되고 **빈 문자열**이 나옵니다.
 * 타입 검사도 린트도 통과하고 예외도 안 나서, 모델이 빈 자료를 받아 "내용이 없다"고 답하거나
 * 아예 없는 내용을 지어낼 때까지 아무도 눈치채지 못했습니다(2026-08-27).
 */

/**
 * 모델에 넘길 글자 수 상한입니다.
 *
 * 슬라이드 100장이면 수만 자가 나오는데, 그대로 넘기면 입력 토큰만으로 비용이 뜁니다. 발표
 * 자료는 앞부분에 목차와 핵심이 몰려 있어서 뒤를 자르는 편이 손실이 적습니다.
 */
export const DECK_TEXT_MAX_LENGTH = 20_000;

/**
 * 요약할 가치가 있는 최소 글자 수입니다.
 *
 * 이 선이 없으면 자료에서 글자를 거의 못 뽑았을 때도 모델을 부릅니다. 그러면 둘 중 하나가
 * 나오는데 **둘 다 나쁩니다** — "내용이 없다"는 요약이 나오거나, 지어내지 말라는 지시에도
 * 모델이 그럴듯한 남의 이야기를 지어냅니다(2026-08-27 실측: 자료 텍스트 없이 나간 호출이
 * 의료 AI 이야기를 통째로 만들어 냈습니다). 후자는 강연자가 알아차리기 어렵고, 그대로 리포트에
 * 실려 굳습니다.
 *
 * 표지와 목차만 읽혀도 이 정도는 넘습니다. 못 넘으면 자료를 못 읽은 것으로 보는 게 맞습니다.
 */
export const MIN_DECK_TEXT_LENGTH = 200;
